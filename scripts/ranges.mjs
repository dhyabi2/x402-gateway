#!/usr/bin/env node
/**
 * Regenerate src/ranges.js from the address lists crawler operators publish.
 *
 *   node scripts/ranges.mjs        # rewrite src/ranges.js, then commit and release
 *
 * The lists move (OpenAI's chatgpt-user.json changes every few weeks), and a
 * stale copy fails in one direction only: a real crawler from a new block is
 * metered or, for the search crawlers, charged as an impostor. Run this before
 * every release.
 */
import { writeFile } from 'node:fs/promises';

const SOURCES = {
  googlebot: 'https://developers.google.com/static/search/apis/ipranges/googlebot.json',
  bingbot: 'https://www.bing.com/toolbox/bingbot.json',
  duckduckbot: 'https://duckduckgo.com/duckduckbot.json',
  oaiSearchbot: 'https://openai.com/searchbot.json',
  chatgptUser: 'https://openai.com/chatgpt-user.json',
  perplexitybot: 'https://www.perplexity.ai/perplexitybot.json',
  perplexityUser: 'https://www.perplexity.ai/perplexity-user.json',
};
const CLOUDFLARE = ['https://www.cloudflare.com/ips-v4', 'https://www.cloudflare.com/ips-v6'];

const get = async (url) => {
  const res = await fetch(url, { headers: { 'user-agent': 'Mozilla/5.0 (x402-gateway ranges refresh)' } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res;
};

const out = {};
for (const [name, url] of Object.entries(SOURCES)) {
  const body = await (await get(url)).json();
  out[name] = body.prefixes.map((p) => p.ipv4Prefix ?? p.ipv6Prefix).filter(Boolean);
  if (!out[name].length) throw new Error(`${url}: no prefixes`);
}
out.cloudflare = [];
for (const url of CLOUDFLARE) out.cloudflare.push(...(await (await get(url)).text()).split(/\s+/).filter(Boolean));

const day = new Date().toISOString().slice(0, 10);
let src = `// Generated by scripts/ranges.mjs on ${day} from each operator's published list. Do not edit by hand.\n`;
src += `export const FETCHED = '${day}';\n\n`;
for (const [name, list] of Object.entries(out)) {
  src += `export const ${name} = [\n${list.map((c) => `  '${c}',`).join('\n')}\n];\n\n`;
}
await writeFile(new URL('../src/ranges.js', import.meta.url), src);
console.log(Object.entries(out).map(([k, v]) => `${k}=${v.length}`).join(' '));
