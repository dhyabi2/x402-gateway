/**
 * Headless browsers that say so. Nobody reads a page through one of these; a
 * scrape does, and it runs the page's scripts while it is at it. Lightpanda was
 * 151k requests from 63k addresses on one site in a day (2026-10-19). They do
 * not read robots.txt, so they are charged, never named there.
 */
/**
 * Crawlers that feed an AI answer engine's own index: meta-webindexer, YouBot,
 * ExaSearchBot, AionBot. 0.9.0 charged them; Anthony's call on 2026-10-19 was
 * the other way ("allow ... ai chat bots"), so since 0.10.0 they are retrieval
 * crawlers: named welcome in robots.txt and never metered. The list stays
 * exported for a site that wants to charge them anyway (`aiIndex`).
 */
export const AI_INDEX_AGENTS = ['meta-webindexer', 'YouBot', 'ExaSearchBot', 'AionBot'];

export const HEADLESS_AGENTS = ['Lightpanda', 'HeadlessChrome', 'PhantomJS'];

/**
 * Retrieval crawlers and AI chat fetchers, named in robots.txt so their
 * operators can see they are welcome, and never metered: a person asked an
 * assistant about this page and the fetch is that person reading it.
 * Google-Extended is Google's training token but Google documents it as also
 * gating grounding in the Gemini app, so it stays on this side.
 *
 * Where the operator publishes its addresses (OpenAI, Perplexity) the name is
 * only believed from them: see VERIFIED_RETRIEVAL. The rest are believed by
 * name, which a swarm can copy; ThreatCrush's repeat-402 ladder is the
 * backstop for that, not this list.
 */
export const RETRIEVAL_AGENTS = [
  'OAI-SearchBot',
  'ChatGPT-User',
  'Claude-SearchBot',
  'Claude-User',
  'PerplexityBot',
  'Perplexity-User',
  'Google-Extended',
  'Bingbot',
  'Meta-ExternalFetcher',
  'DuckAssistBot',
  'MistralAI-User',
  ...AI_INDEX_AGENTS,
];

const lower = (list) => list.map((t) => t.toLowerCase());

/**
 * Whether a user agent is one of `agents` (default: the training list).
 *
 * Substring match on the documented token, which a determined caller can lie
 * about. That is fine and worth being clear about: this identifies a
 * self-declared corpus crawler so it can be charged. It does not stop anything
 * hostile, and a crawler wearing a browser's user agent walks straight past it.
 */
export function isTrainingAgent(userAgent = '', agents = TRAINING_AGENTS) {
  const ua = String(userAgent ?? '').toLowerCase();
  if (!ua) return false;
  return lower(agents).some((t) => ua.includes(t));
}

/**
 * Search crawlers that are welcome everywhere, with the address ranges their
 * operators publish. A user agent alone is not enough to spare a caller --
 * "Googlebot" is the first string a scraper copies -- so a crawler is only
 * spared when its address agrees with its name, and a request that wears one
 * of these names from an address outside the list is an impostor and is
 * charged (`chargeImpostors`).
 *
 * The lists are the operators' own (src/ranges.js, regenerated by
 * scripts/ranges.mjs before each release): googlebot.json, bingbot.json,
 * duckduckbot.json, Cloudflare's ips-v4/ips-v6 for its own crawlers
 * (Always Online, health checks, Radar), and Apple's 17.0.0.0/8 plus its
 * AS714 IPv6 blocks for Applebot.
 */
export const WELCOME_CRAWLERS = [
  { token: 'Googlebot', cidrs: R.googlebot },
  { token: 'bingbot', cidrs: R.bingbot },
  { token: 'Applebot', cidrs: ['17.0.0.0/8', '2620:149::/32', '2a01:b740::/32'] },
  { token: 'DuckDuckBot', cidrs: R.duckduckbot },
  { token: 'Cloudflare-', cidrs: R.cloudflare },
];

